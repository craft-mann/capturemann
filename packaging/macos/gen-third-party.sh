#!/usr/bin/env bash
# Generates THIRD_PARTY_LICENSES.md: the licenses of every crate that is linked into the macOS
# bundle (cm-desktop, cm-overlay, cm-cli, cm-mcp; normal dependencies only, target
# aarch64-apple-darwin plus x86_64-apple-darwin) and of the bundled fonts. Identical license
# texts are printed once with the list of crates that use them. Offline: reads cargo metadata and
# the crate sources already in the cargo registry (run `cargo fetch` first on a clean machine).
#
# Usage: packaging/macos/gen-third-party.sh [output-file]   (default: THIRD_PARTY_LICENSES.md)
set -euo pipefail
die() { echo "gen-third-party.sh: $*" >&2; exit 1; }
command -v cargo >/dev/null 2>&1 || die "cargo not found"
command -v python3 >/dev/null 2>&1 || die "python3 not found"
root="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
out="${1:-$root/THIRD_PARTY_LICENSES.md}"
tmp="$(mktemp -d "${TMPDIR:-/tmp}/cm-licenses.XXXXXX")"
trap 'rm -rf "$tmp"' EXIT
for triple in aarch64-apple-darwin x86_64-apple-darwin; do
  (cd "$root" && cargo metadata --format-version 1 --locked --filter-platform "$triple" > "$tmp/$triple.json")
done
python3 - "$root" "$out" "$tmp" <<'PY'
import glob, hashlib, json, os, sys
root, out, tmp = sys.argv[1:4]
roots = {"cm-desktop", "cm-overlay", "cm-cli", "cm-mcp"}
pkgs, shipped = {}, set()
for triple in ("aarch64-apple-darwin", "x86_64-apple-darwin"):
    m = json.load(open(f"{tmp}/{triple}.json"))
    byid = {p["id"]: p for p in m["packages"]}
    nodes = {n["id"]: n for n in m["resolve"]["nodes"]}
    todo = [i for i, p in byid.items() if p["name"] in roots and p["source"] is None]
    seen = set(todo)
    while todo:
        n = nodes[todo.pop()]
        for d in n["deps"]:
            if any(k["kind"] is None for k in d["dep_kinds"]) and d["pkg"] not in seen:
                seen.add(d["pkg"]); todo.append(d["pkg"])
    for i in seen:
        p = byid[i]
        if p["source"] is None:
            continue  # workspace crates: Apache-2.0, covered by LICENSE
        pkgs[(p["name"], p["version"])] = p
        shipped.add((p["name"], p["version"]))
texts = {}      # sha -> (text, [crate ids])
spdx = {}       # license expression -> [crates]
missing = []
for (name, ver), p in sorted(pkgs.items()):
    spdx.setdefault(p["license"] or "UNKNOWN", []).append(f"{name} {ver}")
    d = os.path.dirname(p["manifest_path"])
    def lic_files(dd):
        return sorted(f for f in glob.glob(dd + "/*") if os.path.isfile(f)
                      and os.path.basename(f).upper().startswith(("LICENSE", "LICENCE", "COPYING", "NOTICE", "UNLICENSE")))
    files = lic_files(d)
    if not files:  # a crate that vendors a C/C++ project keeps its license a folder down (whisper-rs-sys: whisper.cpp)
        files = sorted(f for sub in sorted(glob.glob(d + "/*/")) for f in lic_files(sub.rstrip("/")))
    up = d
    for _ in range(3):  # monorepo crates (git dependencies) keep the license at the repository root
        if files or p["source"].startswith("registry"):
            break
        up = os.path.dirname(up)
        files = lic_files(up)
    if not files:
        missing.append(f"{name} {ver}")
    for f in files:
        t = open(f, encoding="utf-8", errors="replace").read().strip()
        h = hashlib.sha256(" ".join(t.split()).encode()).hexdigest()
        texts.setdefault(h, (t, []))[1].append(f"{name} {ver}")
fonts = [("Geist, Geist Mono (apps/desktop, design/fonts)", "apps/desktop/assets/fonts/OFL-LICENSE.txt"),
         ("Inter (cm-render)", "crates/cm-render/assets/Inter-LICENSE.txt"),
         ("Noto Sans SC subset (cm-render)", "crates/cm-render/assets/NotoSansSC-LICENSE.txt"),
         ("Noto Emoji (cm-render)", "crates/cm-render/assets/NotoEmoji-LICENSE.txt")]
icons = [("Lucide icons (apps/desktop/assets/icons; ISC, with portions MIT from Feather)", "apps/desktop/assets/icons/LICENSE"),
         ("OneDrive and Dropbox marks (apps/desktop/assets/icons; MIT: Flexicon by Blivesta, Fontisto by Kenan Gundogan)", "apps/desktop/assets/icons/BRAND-LICENSE.txt")]
w = []
w.append("# Third-party licenses\n")
w.append("CaptureMann is Apache-2.0 (see LICENSE). This file lists the third-party components that ship in the macOS app bundle.\n"
         "It is generated by `packaging/macos/gen-third-party.sh` (`make licenses`); do not edit by hand.\n")
w.append("## Mozilla Public License 2.0 components\n")
w.append("Some crates are under MPL-2.0 (file-level copyleft). They are used unmodified; their source is available from crates.io "
         "(https://crates.io/crates/<name>) and from the registry sources named below.\n")
for lic, crates in sorted(spdx.items()):
    if "MPL-2.0" in lic:
        w.append(f"- {', '.join(crates)} ({lic})")
w.append("\n## Fonts (SIL Open Font License 1.1)\n")
seen_font = {}
for label, rel in fonts:
    t = open(os.path.join(root, rel), encoding="utf-8", errors="replace").read().strip()
    seen_font.setdefault(t, []).append(label)
for t, labels in seen_font.items():
    w.append("### " + "; ".join(labels) + "\n\n```text\n" + t + "\n```\n")
w.append("## Icons\n")
w.append("The other brand marks (YouTube, TikTok, Facebook, Google Drive) are single paths from Simple Icons (CC0, no notice "
         "required); the marks themselves belong to their owners and only say which service a row is about.\n")
for label, rel in icons:
    t = open(os.path.join(root, rel), encoding="utf-8", errors="replace").read().strip()
    w.append("### " + label + "\n\n```text\n" + t + "\n```\n")
w.append("## Rust crates by license expression\n")
for lic, crates in sorted(spdx.items()):
    w.append(f"- **{lic}**: {len(crates)} crates")
w.append("\nFull crate list:\n")
for (name, ver), p in sorted(pkgs.items()):
    w.append(f"- {name} {ver}: {p['license'] or 'UNKNOWN'}")
w.append("\n## License and notice texts\n")
w.append("Each distinct text is printed once, followed by the crates that carry it.\n")
for h, (t, crates) in sorted(texts.items(), key=lambda kv: kv[1][1][0]):
    w.append("### Used by: " + ", ".join(crates) + "\n\n```text\n" + t + "\n```\n")
if missing:
    w.append("## Crates without a license file in their package\n")
    w.append("These declare their license in Cargo.toml (see the list above) but ship no separate text: " + ", ".join(missing) + "\n")
data = "\n".join(w) + "\n"
open(out, "w", encoding="utf-8").write(data)
print(f"wrote {out}: {len(pkgs)} crates, {len(texts)} distinct texts, {len(data)//1024} KB, {len(missing)} without a file")
PY
